#[test]
fn historical_browser_token_remains_readable_without_a_legacy_writer() {
    // Frozen before the shared-core extraction; never regenerated by this test.
    let token = "bitbid1:AQAFYWxpY2VBBHm+Zn753LusVaBilc6HCwcCm/zbLc4o2VnygVsW+BeYSDradyajxGVdpPv8DhEIqP0XtEimhVQZnEfQj/sQ1LgBAQEBAQEBAQEBAQEAMPcx6YkasDdkcXVIz1Uu6cYGRywV2pcOTmOa6SbII3/gTfAI0d9fUlVeXP7kDEN79AICAgICAgICAgICApCMcmC1mHflxNL2VeqQ1py7cWPk8kzTYJYM+zm4aWxwPQJM";
    assert_eq!(
        seal::unseal_to_string(token, &secret(2)).unwrap(),
        "bitbid fixed vector"
    );
    assert!(matches!(
        seal::unseal(token, &secret(3)),
        Err(TokenError::Legacy(_))
    ));
    assert!(matches!(
        seal::unseal("bitbid1:Ag==", &secret(2)),
        Err(TokenError::Legacy(_))
    ));
}

#[test]
fn malformed_tokens_wrong_keys_and_tampering_fail_at_public_boundary() {
    assert!(seal::seal_to_share_string(b"test", "invalid key").is_err());
    assert!(matches!(
        seal::unseal("bitbid2:!", &secret(2)),
        Err(TokenError::Protocol(protocol::ProtocolError::Base64(_)))
    ));
    let unknown_version = CANONICAL.replace("\"protocol_version\":1", "\"protocol_version\":2");
    assert!(matches!(
        seal::unseal(&unknown_version, &secret(2)),
        Err(TokenError::Protocol(protocol::ProtocolError::Version(2)))
    ));
    assert!(seal::unseal(CANONICAL, &secret(3)).is_err());
    assert!(seal::unseal(CANONICAL, &[0; 31]).is_err());

    let mut tampered = protocol::decode_payload(CANONICAL.trim().as_bytes()).unwrap();
    tampered.content.replace_range(17..18, "A");
    assert!(seal::unseal(&protocol::to_share_string(&tampered).unwrap(), &secret(2)).is_err());
    assert!(registry::decode_get_secret_info_response(r#"{"result":"0x1234"}"#, "test").is_err());
    assert!(address::hex_to_bytes("0xabc").is_err());
}

#[test]
fn browser_single_body_boundary_preserves_bundle_and_encoding_errors() {
    let mut payload = protocol::decode_payload(CANONICAL.trim().as_bytes()).unwrap();
    payload.members = Some(vec![]);
    assert!(matches!(
        seal::unseal(&protocol::to_share_string(&payload).unwrap(), &secret(2)),
        Err(TokenError::Bundle)
    ));
    payload.members = None;
    payload.content_encoding = Some("unknown".into());
    assert!(matches!(
        seal::unseal(&protocol::to_share_string(&payload).unwrap(), &secret(2)),
        Err(TokenError::Encoding)
    ));
}
